# read in data
tpm <- read.table('./Lumbar_Spinal_Cord/Lumbar_Spinal_Cord_gene_tpm.tsv', header = T, row.names = 1, sep = '\t')
meta <- read.table('./Lumbar_Spinal_Cord/Lumbar_Spinal_Cord_metadata.tsv', header = T, row.names = 1, sep = '\t')
table(duplicated(tpm$gene_name))
#FALSE  TRUE 
#57317  1567 

gene <- c('COL1A1','COL1A2','DCN','LUM','THBS2','CLDN1','GADL1') # COL1A2

df <- tpm[which(tpm$gene_name %in% gene),]
rownames(df) <- df$gene_name
df <- df[,-1]
df <- as.data.frame(t(df))
df <- cbind(df,meta[rownames(df),c('disease','disease_duration')])
df$disease <- ifelse(df$disease=='Control','Control','ALS') # for some case is ALS-FTD

library(ggplot2)
library(ggpubr)
library(ggsci)

df2 <- reshape2::melt(df, id.vars = c('disease','disease_duration'), variable.name = 'gene', value.name = 'expression')
df2$gene <- factor(df2$gene, levels = gene)
df2$disease <- factor(df2$disease,levels = c('Control','ALS'))

theme_set(theme_grey(base_family = "sans")) 
pdf('./Lumbar_Spinal_Cord_boxplot.pdf', width = 10, height = 5)
ggplot(df2, aes(x=disease, y=expression)) +
  geom_boxplot(aes(fill = disease),outlier.shape = NA) +
  #geom_jitter(aes(color=disease),position = position_jitter(width = 0.2),) +
  geom_jitter(aes(fill = disease),
              shape = 21,
              color = "black",
              width = 0.2,
              size = 1.5,
              stroke = 0.6,
              alpha = 0.8)+
  facet_wrap(~gene,scales='free',ncol=length(gene))+
  #theme_classic() +
  labs(title = 'Bulk RNA-seq of human lumbar spinal cord') +
  stat_compare_means(method = 'wilcox.test',
                     comparisons = list(c("Control","ALS")),
                     label = "p.signif") +
  theme(
    axis.text = element_text(color = 'black'),
    strip.background = element_rect(fill = "lightblue", color = 'black'),
    strip.text = element_text(face='italic') 
  )+ scale_fill_manual(values = c('#4DBBD5','#E64B35'))+
  scale_color_manual(values = c('#4DBBD5','#E64B35'))
