# data from GSE137810, which covered 2906 samples
# the sample meta data is downloaded from https://ftp.ncbi.nlm.nih.gov/geo/series/GSE137nnn/GSE137810/matrix/
# two files (platforms) are porvided, GPL24676 and GPL24677, which are generated by two different sequencing platforms (Illumina NovaSeq 6000 and Illumina HiSeq 4000, respectively).
# the count data is downloaded from https://www.ncbi.nlm.nih.gov/geo/query/acc.cgi?acc=GSE137810#:~:text=144.7%20Mb-,(http),-(custom)
# However only 731 samples have count data
# Two different platforms (GPL24676 and GPL24677) are used for sequencing, 
# and the count data is only available for samples sequenced by GPL24676 (555/731). 
# Therefore, we will only use the samples sequenced by GPL24676 for downstream analysis. 
# also considering the tech-batch, combining two platforms may not be a good idea.


setwd('./bulk-seq/cortex')

# count files
files <- list.files('./bulk-seq/cortex/GSE137810_RAW/', pattern = 'counts.txt.gz', full.names = F)
samples <- sapply(strsplit(files,'_'), '[',2)
ges <- sapply(strsplit(files,'_'), '[',1)
table(duplicated(samples)) # FALSE 713  TRUE  18 
table(duplicated(ges)) # unique sample names and unique GEO accessions


# process meta 1 (GPL24676)
# selected 5 fields: sample_geo_accession, tissue, subject id, group, sample id alt from GSE137810-GPL24676_series_matrix.txt.gz
meta <- read.csv('./GSE137810-GPL24676_series_matrix_selected_0423.csv',header = F)
meta <- meta[,c(1,which(meta[3,] %in% ges))]
meta <- meta[c(3,9,12,13,14),]
m <- c('sample_geo_accession','tissue','disease state','gender','subject id')
rownames(meta) <- m
meta$V1 <- NULL
for (field in m) {
  meta[field,] <- str_replace(meta[field,], paste0(field, ': '), '')
}
meta <- t(meta) %>% as.data.frame()
rownames(meta) <- meta$sample_geo_accession
spinalcord <- grepl('spinal cord',meta$tissue,ignore.case = T)
meta_ctx <- meta[!spinalcord,] # I only want ctx data here, not spinal cord samples
meta_ctx <- subset(meta_ctx,meta_ctx$`disease state` %in% c('ALS','CTL')) # only keep control and SALS samples)


for(i in seq_along(files)){
  print(i)
  count <- data.table::fread(paste0('./GSE137810_RAW/',files[i]))
  colnames(count) <- c('gene_name',ges[i])
  if(!exists('count_all')){
    count_all <- count
  }else{
    count_all <- merge(count_all, count, by = 'gene_name', all = T)
  }
}
write.csv(count_all,'./GSE137810_count_all.csv',row.names = F)
